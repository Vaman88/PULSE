const {readFileSync} = require('node:fs');
const {runInNewContext} = require('node:vm');
const assert = require('node:assert/strict');
const context = {};
runInNewContext(readFileSync(__dirname+'/public/barcode.js','utf8'), context);
const parse = context.productBarcode;
const upc = '036000291452', gtin = '00036000291452';
assert.equal(parse(upc), gtin);
assert.equal(parse(gtin), gtin);
assert.equal(parse(']E0'+upc+'\r\n'), gtin);
assert.equal(parse(']d201'+gtin+'1727123110LOT123\x1d21SERIAL1'), gtin);
assert.equal(parse(']d201'+gtin+'1728123110LOT456\x1d21SERIAL2'), gtin);
assert.equal(parse('(01)'+gtin+'(17)271231(10)LOT123'), gtin);
assert.equal(parse('01'+gtin+'17271231'), gtin);
assert.equal(parse('LOCAL-SKU-123'), 'LOCAL-SKU-123');
assert.throws(() => parse('036000291453'), /check digit/);
assert.throws(() => parse(']d210LOT123'), /GTIN/);
assert.throws(() => parse('ABC\x1d123'), /keyboard output/);
assert.throws(() => parse(''), /Scan one/);
assert.throws(() => parse('x'.repeat(513)), /Scan one/);
console.log('Barcode checks passed: UPC/GTIN equivalence, GS1 product matching across lots and serials, scanner prefixes, invalid scans.');
